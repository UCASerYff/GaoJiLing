"""Verify real Shell tray lifecycle without showing or activating a window."""

import argparse
import ctypes
from pathlib import Path
import sys
import time

from smoke_icon_assets import window_icon_bitmap


def smoke(icon):
    from gaojiling import win32 as win

    module = win.module_handle(None)
    name = "GaoJiLing.IndependentTrayApiFixture"
    callback = win.WNDCALL(win.def_window_proc)
    description = win.WindowClass(callback=callback, module=module, name=name)
    assert win.register_class(ctypes.byref(description))
    original = win.notify_icon
    hwnd = None
    tray = None
    events = []
    registered_icons = []
    try:
        hwnd = win.create_window(0, name, name, 0, 0, 0, 0, 0, None, None, module, None)
        assert hwnd

        def measure(action, data):
            record = ctypes.cast(data, ctypes.POINTER(win.NotifyData)).contents
            assert record.hwnd == hwnd and record.id == win.NOTIFY_ID
            if action == 0:
                registered_icons.append(window_icon_bitmap(record.icon))
            result = bool(original(action, data))
            events.append((action, result))
            return result

        def rectangle():
            identifier = win.NotifyIdentifier(size=ctypes.sizeof(win.NotifyIdentifier), hwnd=hwnd, id=win.NOTIFY_ID)
            return win.notify_rect(ctypes.byref(identifier), ctypes.byref(win.w.RECT())) == 0

        win.notify_icon = measure
        tray = win.Tray(hwnd, icon)
        tray.tooltip("搞机灵 · 隔离 Shell 核验")
        assert tray.available and tray.owns_icon
        dpi = win.window_dpi(win.find_window("Shell_TrayWnd", None) or hwnd)
        dimensions = win.icon_dimensions(dpi, small=True)
        reference = win.load_sized_icon(icon, dimensions)
        assert reference
        try:
            expected = window_icon_bitmap(reference)
        finally:
            win.destroy_icon(reference)
        time.sleep(0.25)
        initial = rectangle()
        assert measure(2, ctypes.byref(tray._data()))
        assert tray.register()
        time.sleep(0.25)
        restored = rectangle()
        tray.close()
        final = rectangle()
        print(f"Actual Shell API results: {events}")
        print(f"Shell icon rectangle after add/re-add/delete: {initial}/{restored}/{final}")
        assert events == [(0, True), (4, True), (1, True), (2, True), (0, True), (4, True), (2, True)]
        assert initial and restored and not final
        assert registered_icons == [expected, expected] and expected[0] == dimensions
        print(f"Shell at {dpi} DPI: both NIM_ADD calls received {dimensions[0]}x{dimensions[1]} packaged icon pixels.")
    finally:
        if tray:
            tray.close()
        win.notify_icon = original
        if hwnd:
            win.destroy_window(hwnd)
        win.unregister_class(name, module)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("icon", type=Path, help="The AppIcon.ico generated by the Windows build")
    args = parser.parse_args()
    if sys.platform != "win32":
        parser.error("This smoke requires Windows")
    sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
    smoke(args.icon.resolve(strict=True))
